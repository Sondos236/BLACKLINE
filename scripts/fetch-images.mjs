async function processOne([out, id, width]) {
  const file = path.join(OUT, `${out}.jpg`);
  const url = `https://images.unsplash.com/${id}?w=${width}&q=90&fm=jpg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`);
  const input = Buffer.from(await res.arrayBuffer());

  // The BLACKLINE grade: monochrome, deeper blacks, gently lifted contrast.
  const graded = sharp(input).grayscale().gamma(2.2, 2.0).linear(1.12, -14);

  await fs.mkdir(path.dirname(file), { recursive: true });
  const info = await graded.clone().jpeg({ quality: 78, mozjpeg: true, progressive: true }).toFile(file);

  const blur = await graded.clone().resize(16).jpeg({ quality: 50 }).toBuffer();
  console.log(`✓ ${out} ${info.width}x${info.height} ${(info.size / 1024).toFixed(0)}KB`);
  return [
    `/images/${out}.jpg`,
    { width: info.width, height: info.height, blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}` },
  ];
}

const entries = [];
for (const src of SOURCES) entries.push(await processOne(src));

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");

await fs.mkdir(path.dirname(MANIFEST), { recursive: true });
await fs.writeFile(
  MANIFEST,
  `// Generated by scripts/fetch-images.mjs — do not edit by hand.\n` +
    `export interface ImageMeta {\n  width: number;\n  height: number;\n  blurDataURL: string;\n}\n\n` +
    `export const imageManifest: Record<string, ImageMeta> = {\n${body}\n};\n`,
);
console.log(`\nWrote ${entries.length} entries to ${path.relative(ROOT, MANIFEST)}`);
